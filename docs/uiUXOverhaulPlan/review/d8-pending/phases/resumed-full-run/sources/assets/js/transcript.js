'use strict';
// One read-only transcript owner per utility panel; media stays in player.js.
(function () {
    var instances = new WeakMap();
    window.InvidiousTranscript = function (panel, video, labels) {
        if (instances.has(panel)) return instances.get(panel);
        var ui = window.InvidiousUI, storage = window.InvidiousStorage;
        var language = panel.querySelector('#transcript-language'), search = panel.querySelector('#transcript-search');
        var status = panel.querySelector('#transcript-status'), retry = panel.querySelector('#transcript-retry');
        var container = panel.querySelector('#transcript-lines'), follow = panel.querySelector('#transcript-follow');
        var life = new AbortController(), request = null, generation = 0, activePage = true, visible = false, disposed = false, frame = null;
        var cache = new Map(), current = null, activeLine = null, rows = new Map();
        function on(target,name,handler,options) { target.addEventListener(name,handler,Object.assign({signal:life.signal},options)); }
        function alive() { return activePage && !disposed && panel.isConnected && storage.isCurrent() && !(player.isDisposed && player.isDisposed()); }
        function displayed() {
            var owner = panel.closest('[role=tabpanel]');
            return panel.isConnected && !panel.hidden && (!owner || !owner.hidden) && panel.getClientRects().length > 0;
        }
        function cancel() {
            generation++; if (request) request.abort(); request = null;
            container.setAttribute('aria-busy','false');
        }
        function position() {
            if (!current) return -1;
            var time = player.currentTime()*1000, body = current.body, low = 0, high = body.length-1, found = -1;
            while (low <= high) {
                var middle = (low+high)>>1;
                if (body[middle].start <= time) { found = middle; low = middle+1; } else high = middle-1;
            }
            if (found >= 0 && body[found].duration !== null && time >= body[found].start+body[found].duration) return -1;
            return found;
        }
        function track() {
            if (!alive() || !visible || !current) return;
            var next = rows.get(position()) || null;
            if (next === activeLine) return;
            if (activeLine) { activeLine.classList.remove('is-active'); activeLine.removeAttribute('aria-current'); }
            activeLine = next;
            if (!next) return;
            next.classList.add('is-active'); next.setAttribute('aria-current','true');
            if (follow.checked && !search.value.trim()) {
                // Only this viewport scrolls. Manual input turns Follow off.
                var top = next.getBoundingClientRect().top-container.getBoundingClientRect().top+container.scrollTop;
                container.scrollTop = Math.max(0,top-container.clientHeight/3);
            }
        }
        function timestamp(ms) {
            var seconds = Math.floor(ms/1000);
            return (seconds >= 3600 ? Math.floor(seconds/3600)+':' : '')+String(Math.floor(seconds/60)%60).padStart(2,'0')+':'+String(seconds%60).padStart(2,'0');
        }
        function render() {
            if (!alive() || !current) return;
            var term = search.value.trim().toLocaleLowerCase(), fragment = document.createDocumentFragment(), count = 0;
            rows.clear(); activeLine = null;
            current.body.forEach(function (line,index) {
                if (term && !line.text.toLocaleLowerCase().includes(term)) return;
                var row = document.createElement('div'); row.className = 'transcript-line';
                var button = document.createElement('button'); button.type = 'button'; button.className = 'text-button transcript-time'; button.textContent = timestamp(line.start);
                button.addEventListener('click',function () { if (alive() && visible) player.currentTime(line.start/1000); });
                var text = document.createElement(line.heading ? 'h3' : 'p'); text.textContent = line.text; text.dir = 'auto';
                row.append(button,text); fragment.append(row); rows.set(index,row); count++;
            });
            container.replaceChildren(fragment); track();
            container.tabIndex = count ? 0 : -1; retry.hidden = current.body.length > 0;
            status.textContent = !count ? (term ? labels.no_matches : labels.transcript_empty) : current.autoGenerated ? labels.auto_generated : '';
        }
        function normalize(data) {
            if (!data || !data.transcript || !Array.isArray(data.transcript.body)) throw new Error('Invalid transcript');
            var input = data.transcript.body;
            var body = input.map(function (line,index) {
                if (!line || typeof line.line !== 'string' || !Number.isFinite(line.startMs) || line.startMs < 0) return null;
                return {text:line.line,start:line.startMs,duration:Number.isFinite(line.durationMs) && line.durationMs > 0 ? line.durationMs : null,heading:line.type === 'heading',order:index};
            }).filter(Boolean).sort(function (a,b) { return a.start-b.start || a.order-b.order; });
            if (input.length && !body.length) throw new Error('Invalid transcript lines');
            return {body:body,autoGenerated:data.transcript.autoGenerated === true};
        }
        async function load(force) {
            if (!alive() || !visible) return;
            cancel(); var token = generation, selected = language.value, controller = new AbortController(); request = controller;
            current = null; rows.clear(); activeLine = null; container.replaceChildren(); retry.hidden = true;
            container.tabIndex = -1; if (force === true) cache.delete(selected);
            if (cache.has(selected)) {
                current = cache.get(selected); cache.delete(selected); cache.set(selected,current); request = null; render(); return;
            }
            status.textContent = labels.loading; container.setAttribute('aria-busy','true');
            try {
                var data = await ui.request('/api/v1/transcripts/'+encodeURIComponent(video.id)+'?label='+encodeURIComponent(selected),{signal:controller.signal});
                if (!alive() || !visible || token !== generation || controller.signal.aborted || language.value !== selected) return;
                current = normalize(data); cache.set(selected,current);
                while (cache.size > 5) cache.delete(cache.keys().next().value);
                render();
            } catch (error) {
                if (!alive() || !visible || token !== generation || controller.signal.aborted) return;
                status.textContent = error.status === 404 ? labels.transcript_unavailable || labels.transcript_error : labels.transcript_error;
                retry.hidden = false;
            } finally {
                if (token === generation && !controller.signal.aborted) { request = null; container.setAttribute('aria-busy','false'); }
            }
        }
        function setVisible(value) {
            if (!alive()) return;
            var next = value === true && displayed();
            if (visible === next) return;
            visible = next;
            if (!next) { cancel(); cancelAnimationFrame(frame); frame = null; return; }
            if (current) { activeLine = null; track(); } else load();
        }
        function dispose() {
            if (disposed) return;
            cancel(); disposed = true; activePage = false; visible = false; life.abort(); cancelAnimationFrame(frame);
            player.off('timeupdate',track); player.off('seeked',track); player.off('dispose',dispose);
            cache.clear(); rows.clear(); current = null; activeLine = null; instances.delete(panel);
        }
        function suspend(event) {
            cancel(); activePage = false; visible = false; cancelAnimationFrame(frame); frame = null;
            if (!event.persisted) dispose();
        }
        on(container,'wheel',function () { follow.checked = false; },{passive:true});
        on(container,'touchstart',function () { follow.checked = false; },{passive:true});
        on(container,'pointerdown',function () { follow.checked = false; },{passive:true});
        on(container,'keydown',function (event) { follow.checked = false; event.stopPropagation(); });
        on(follow,'change',function () { activeLine = null; track(); });
        on(search,'input',function () {
            follow.checked = false; cancelAnimationFrame(frame);
            frame = requestAnimationFrame(function () { frame = null; render(); });
        });
        on(language,'change',function () { load(); }); on(retry,'click',function () { load(true); });
        on(window,'pagehide',suspend);
        on(window,'pageshow',function () { activePage = !disposed; if (alive()) setVisible(displayed()); });
        on(window,'browserprofilechange',dispose);
        on(document,'iv:content-added',function () { if (!panel.isConnected) dispose(); });
        player.on('timeupdate',track); player.on('seeked',track); player.on('dispose',dispose);
        var owner = {setVisible:setVisible,dispose:dispose}; instances.set(panel,owner); setVisible(displayed()); return owner;
    };
})();
