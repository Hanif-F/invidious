'use strict';
// Loaded by watch.js on demand. Transcript failures are isolated from the player.
window.InvidiousTranscript = function (panel, video, labels) {
    var language = document.getElementById('transcript-language');
    var search = document.getElementById('transcript-search');
    var status = document.getElementById('transcript-status');
    var retry = document.getElementById('transcript-retry');
    var container = document.getElementById('transcript-lines');
    var cache = Object.create(null);
    var current;
    var generation = 0;

    function timestamp(ms) {
        var seconds = Math.floor(ms / 1000);
        return (seconds >= 3600 ? Math.floor(seconds / 3600) + ':' : '') +
            String(Math.floor(seconds / 60) % 60).padStart(2, '0') + ':' + String(seconds % 60).padStart(2, '0');
    }
    function render() {
        if (!current) return;
        var term = search.value.trim().toLocaleLowerCase();
        var fragment = document.createDocumentFragment();
        var count = 0;
        current.body.forEach(function (line) {
            if (typeof line.line !== 'string' || !Number.isFinite(line.startMs) || line.startMs < 0) return;
            if (term && !line.line.toLocaleLowerCase().includes(term)) return;
            count++;
            var row = document.createElement('div');
            row.className = 'transcript-line';
            var button = document.createElement('button');
            button.type = 'button';
            button.textContent = timestamp(line.startMs);
            button.onclick = function () { player.currentTime(line.startMs / 1000); };
            var text = document.createElement(line.type === 'heading' ? 'h3' : 'p');
            text.textContent = line.line;
            row.appendChild(button);
            row.appendChild(text);
            fragment.appendChild(row);
        });
        container.textContent = '';
        container.appendChild(fragment);
        status.textContent = !count ? (term ? labels.no_matches : labels.transcript_empty) :
            (current.autoGenerated ? labels.auto_generated : '');
    }
    function load() {
        var request = ++generation;
        var label = language.value;
        current = null;
        container.textContent = '';
        retry.hidden = true;
        container.setAttribute('aria-busy', 'false');
        if (cache[label]) { current = cache[label]; render(); return; }
        status.textContent = labels.loading;
        container.setAttribute('aria-busy', 'true');
        function failed() {
            if (request !== generation) return;
            container.setAttribute('aria-busy', 'false');
            status.textContent = labels.transcript_error;
            retry.hidden = false;
        }
        helpers.xhr('GET', '/api/v1/transcripts/' + encodeURIComponent(video.id) + '?label=' + encodeURIComponent(label), {}, {
            on200: function (response) {
                if (request !== generation) return;
                if (!response || !response.transcript || !Array.isArray(response.transcript.body)) { failed(); return; }
                cache[label] = response.transcript;
                current = response.transcript;
                container.setAttribute('aria-busy', 'false');
                render();
            },
            onNon200: failed,
            onError: failed,
            onTimeout: failed
        });
    }
    search.addEventListener('input', render);
    language.addEventListener('change', load);
    retry.onclick = load;
    load();
};
